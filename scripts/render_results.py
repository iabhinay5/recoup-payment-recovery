"""Render docs/RESULTS.md from the measured results files.

Run:  python scripts/render_results.py

Nothing in this project has cost more than numbers copied by hand. The headline moved from
+9.8pp to +10.8pp to +10.7pp, and every move was a transcription or a configuration nobody
recorded — never a change in what the system does. ADR-010 fixed the *storage* of results;
this fixes their *presentation*, which is where a reader actually meets them.

So the results document is not written. It is rendered from ``data/results/eval.json`` and
``data/results/sweep.json``, and every figure in it is read from one of those files. If a
number is wrong here, the run that produced it was wrong — which is a bug worth having,
because it is findable.

Missing or unreadable inputs are a hard failure. A results document with a blank where a
number should be is worse than no document: it looks finished.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

EVAL = Path("data/results/eval.json")
SWEEP = Path("data/results/sweep.json")
OUTPUT = Path("docs/RESULTS.md")

# Internal policy names are keys in the results files; these are what a reader sees.
DISPLAY = {
    "no_retry": "no retry (floor)",
    "fixed_1_3_5_7": "fixed Day-1/3/5/7 *(baseline)*",
    "exponential_backoff": "exponential backoff",
    "aggressive": "aggressive retry",
    "outreach_only": "outreach only",
    "taxonomy_aware": "taxonomy routing",
    "bandit_greedy": "**routing + bandit**",
    "ablation_rail_blind": "rail-blind",
    "ablation_session_blind": "session-blind",
    "ablation_remedy_routed": "remedy-routed",
}

ABLATION_MEANING = {
    "ablation_session_blind": "treats a decline needing a live customer session as an "
    "ordinary timing problem",
    "ablation_rail_blind": "never asks whether the customer's bank is currently down",
    "ablation_remedy_routed": "follows Razorpay's published guidance and asks the customer "
    "instead of retrying a declined card",
}


def load(path: Path) -> dict[str, Any]:
    if not path.exists():
        raise SystemExit(f"{path} is missing. Run the script that produces it first.")
    try:
        return json.loads(path.read_text(encoding="utf-8"))  # type: ignore[no-any-return]
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{path} is not valid JSON: {exc}") from exc


def pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def provenance(document: dict[str, Any], label: str) -> str:
    commit = (document.get("git_commit") or "unknown")[:8]
    dirty = document.get("git_dirty")
    suffix = " (uncommitted changes present)" if dirty else ""
    return f"{label} generated {document['generated_at']} at commit `{commit}`{suffix}"


def headline(ev: dict[str, Any], sw: dict[str, Any]) -> list[str]:
    policies = {p["policy"]: p for p in ev["policies"]}
    base = policies[ev["baseline"]]
    best = policies["bandit_greedy"]
    uplift = (best["recovery_rate"] - base["recovery_rate"]) * 100.0
    cal = ev["calibration"]
    summary = sw["summary"]

    return [
        "# Results",
        "",
        "*This file is generated by `scripts/render_results.py` from "
        "`data/results/eval.json` and `data/results/sweep.json`. Do not edit it by hand — "
        "every number below is read from one of those two files.*",
        "",
        "---",
        "",
        "## The headline",
        "",
        f"**{pct(best['recovery_rate'])} of failed payments recovered, against "
        f"{pct(base['recovery_rate'])} for the industry-standard fixed schedule — "
        f"+{uplift:.1f} percentage points, using {best['attempts_per_episode']:.2f} "
        f"attempts per payment instead of {base['attempts_per_episode']:.2f}.**",
        "",
        "Recovering more while *spending less* is the result worth having. An attempt is "
        "not free: it consumes issuer goodwill, rail capacity, and the customer's patience.",
        "",
        f"Measured over {ev['n_episodes']:,} held-out episodes, exploration off, common "
        "random numbers so every policy meets identical luck on identical episodes.",
        "",
        "### The number is calibrated, not just internally consistent",
        "",
        f"The simulator reproduces Recurly's published recovery rate of "
        f"{pct(cal['published_recovery'])} at {pct(cal['observed_recovery'])} — a gap of "
        f"{abs(cal['delta']) * 100:.2f}pp against a {cal['tolerance'] * 100:.0f}pp "
        f"tolerance. **{cal['verdict']}**",
        "",
        f"Source: {cal['source']}.",
        "",
        "That gate is what makes the rest of this document mean anything. A simulator "
        "tuned only to itself can produce any uplift you like.",
        "",
        "### And it survives the parameters nobody can source",
        "",
        f"Across **{summary['n_configurations']} configurations** — every uncertain "
        f"parameter walked across its full plausible range — the uplift stays between "
        f"**+{summary['uplift_min_pp']:.1f}pp and +{summary['uplift_max_pp']:.1f}pp**. "
        "It is never negative anywhere in the region.",
        "",
        f"The worst case is `{summary['worst_parameter']}` at "
        f"{summary['worst_value']:.4g}, and it still returns "
        f"+{summary['uplift_min_pp']:.1f}pp.",
        "",
    ]


def policy_table(ev: dict[str, Any]) -> list[str]:
    lines = [
        "---",
        "",
        "## Every policy measured",
        "",
        "| policy | recovery | revenue | attempts/ep | wasted attempts | contacts/ep |",
        "|---|---|---|---|---|---|",
    ]
    for p in ev["policies"]:
        lines.append(
            f"| {DISPLAY.get(p['policy'], p['policy'])} | {pct(p['recovery_rate'])} | "
            f"{pct(p['revenue_recovery_rate'])} | {p['attempts_per_episode']:.2f} | "
            f"{pct(p['wasted_attempt_rate'])} | {p['contacts_per_episode']:.2f} |"
        )
    lines += [
        "",
        "A *wasted* attempt is one that did not recover anything. The baseline wastes "
        "roughly two thirds of what it spends; routing on cause is what brings that down.",
        "",
    ]
    return lines


def waste_breakdown(ev: dict[str, Any]) -> list[str]:
    policies = {p["policy"]: p for p in ev["policies"]}
    base = policies[ev["baseline"]]
    best = policies["bandit_greedy"]
    classes = sorted(
        set(base["wasted_by_class"]) | set(best["wasted_by_class"]),
        key=lambda c: -base["wasted_by_class"].get(c, 0),
    )

    lines = [
        "---",
        "",
        "## Where the baseline wastes its attempts",
        "",
        "| decline class | wasted by baseline | wasted by Recoup | avoided |",
        "|---|---|---|---|",
    ]
    spent_more = []
    for name in classes:
        a = base["wasted_by_class"].get(name, 0)
        b = best["wasted_by_class"].get(name, 0)
        delta = a - b
        lines.append(
            f"| `{name}` | {a:,} | {b:,} | {delta:+,} |"
            if delta
            else f"| `{name}` | {a:,} | {b:,} | 0 |"
        )
        if delta < 0:
            spent_more.append((name, -delta))
    lines += [
        "",
        "`session_conditional` is the thesis in one row. Those declines need the customer "
        "back in a live session; a silent retry has probability zero however well timed, "
        "and the fixed schedule spends a large share of its budget there.",
        "",
    ]

    if spent_more:
        detail = ", ".join(f"`{name}` (+{count:,})" for name, count in spent_more)
        lines += [
            f"**Recoup spends *more* wasted attempts than the baseline on {detail}.** That "
            "is deliberate, not a regression. A rail-conditional decline is worth waiting "
            "out and retrying, so a rail-aware policy makes attempts the fixed schedule "
            "never gets around to making — some of which miss. The ablation table below "
            "prices that trade: removing rail awareness entirely costs more recovery than "
            "these extra attempts are worth.",
            "",
        ]
    return lines


def ablations(sw: dict[str, Any]) -> list[str]:
    rows = sw["ablations"]
    baseline_name = sw["baseline"]
    base = rows[baseline_name]["recovery_rate"]
    full = rows["taxonomy_aware"]["recovery_rate"]

    lines = [
        "---",
        "",
        "## Which part of the policy earns the uplift",
        "",
        "Each variant differs from the full routing policy by **exactly one branch**, so "
        "the gap between them attributes the result to that branch and nothing else. "
        "Pinned by `tests/test_ablations.py`, which fails if a variant changes anything "
        "beyond the branch it targets.",
        "",
        f"Measured at {sw['config']['n_customers']:,} customers, "
        f"{sw['config']['bandit_epochs']} bandit epochs.",
        "",
        "| policy | recovery | attempts/ep | vs baseline | branch removed is worth |",
        "|---|---|---|---|---|",
    ]

    order = [
        baseline_name,
        "ablation_session_blind",
        "ablation_rail_blind",
        "ablation_remedy_routed",
        "taxonomy_aware",
        "bandit_greedy",
    ]
    for name in order:
        if name not in rows:
            continue
        m = rows[name]
        gap = (m["recovery_rate"] - base) * 100.0
        worth = f"{(full - m['recovery_rate']) * 100:+.2f}pp" if name in ABLATION_MEANING else "—"
        lines.append(
            f"| {DISPLAY.get(name, name)} | {pct(m['recovery_rate'])} | "
            f"{m['attempts_per_episode']:.2f} | {gap:+.2f}pp | {worth} |"
        )

    lines.append("")
    for name, meaning in ABLATION_MEANING.items():
        if name in rows:
            lines.append(f"- **{DISPLAY.get(name, name)}** — {meaning}.")
    lines.append("")

    session = rows.get("ablation_session_blind")
    if session is not None and session["recovery_rate"] < base:
        lines += [
            f"**Strip out session-awareness and the policy scores "
            f"{pct(session['recovery_rate'])} — below the {pct(base)} baseline it is "
            "supposed to beat.** Almost the whole advantage comes from recognising that "
            "some declines need the customer back rather than another retry. That is the "
            "project's central claim, measured by removing it.",
            "",
        ]

    routed = rows.get("ablation_remedy_routed")
    if routed is not None:
        cost = (full - routed["recovery_rate"]) * 100.0
        lines += [
            f"**Following Razorpay's published guidance costs {cost:.2f}pp.** Razorpay's "
            "documented resolution for `card_declined` is to advise the customer to try "
            "another card, not to silently retry the one that failed. The measurement "
            "says that correctness is nearly free, which is what makes it an easy "
            "decision rather than a trade-off.",
            "",
        ]
    return lines


def sensitivity(sw: dict[str, Any]) -> list[str]:
    lines = [
        "---",
        "",
        "## Sensitivity: what the number rests on",
        "",
        "Every parameter with no trustworthy published value is walked across its full "
        "plausible range with the others held at default. **The bandit is retrained at "
        "every point** — a policy tuned under one set of dynamics is not evidence about "
        "another.",
        "",
        "| parameter | range | worst uplift | best uplift | calibration |",
        "|---|---|---|---|---|",
    ]
    for curve in sw["sensitivity"]:
        ups = [p["uplift_pp"] for p in curve["points"]]
        out = sum(1 for p in curve["points"] if not p["calibration_ok"])
        gate = "ok" if out == 0 else f"**{out} point(s) out**"
        lines.append(
            f"| `{curve['parameter']}` | {curve['low']:g} – {curve['high']:g} | "
            f"+{min(ups):.2f}pp | +{max(ups):.2f}pp | {gate} |"
        )

    lines += [
        "",
        "Every swept parameter is checked to actually affect the simulation by "
        "`TestEverySweptParameterIsLive`. Two once did not: `contact_fatigue_halflife_hours` "
        "was read by nothing at all, and `outage_rate_per_bank_day` had been superseded by "
        "NPCI's per-bank rates. Sweeping them measured nothing while the parameter audit "
        "still reported everything accounted for.",
        "",
    ]

    uncal = sw["summary"]["uncalibrated_points"]
    if uncal:
        lines += [
            "### Where the simulator leaves calibration",
            "",
            f"{len(uncal)} of {sw['summary']['n_configurations']} configurations put the "
            f"baseline outside the "
            f"{sw['calibration_tolerance'] * 100:.0f}pp calibration tolerance:",
            "",
            "| parameter | value | baseline recovery |",
            "|---|---|---|",
        ]
        for point in uncal:
            lines.append(
                f"| `{point['parameter']}` | {point['value']:.4g} | "
                f"{pct(point['baseline_recovery'])} |"
            )
        lines += [
            "",
            "These are reported rather than dropped. At those settings the simulator no "
            "longer reproduces the published baseline, so **no claim in this document "
            "rests on them** — but hiding them would be the more comfortable choice and "
            "the wrong one.",
            "",
        ]
    return lines


def reproducing(ev: dict[str, Any], sw: dict[str, Any]) -> list[str]:
    return [
        "---",
        "",
        "## Reproducing this",
        "",
        "```",
        "python scripts/run_eval.py        # data/results/eval.json",
        "python scripts/run_sweep.py       # data/results/sweep.json",
        "python scripts/render_results.py  # this file",
        "```",
        "",
        "| | configuration | provenance |",
        "|---|---|---|",
        f"| evaluation | {ev['params']['n_customers']:,} customers, seed "
        f"{ev['params']['seed']}, {ev['params']['bandit_epochs']} epochs, "
        f"{ev['n_episodes']:,} held-out episodes | {provenance(ev, '')} |",
        f"| sweep | {sw['config']['n_customers']:,} customers, seed "
        f"{sw['config']['seed']}, {sw['config']['bandit_epochs']} epochs, "
        f"{sw['config']['points_per_parameter']} points per parameter | "
        f"{provenance(sw, '')} |",
        "",
        "Both runs are deterministic. `tests/test_harness.py` re-runs the evaluation under "
        "three different `PYTHONHASHSEED` values and fails if they disagree, because they "
        "once did: an RNG seeded from `hash(payment.id)` made the published figure drift "
        "between runs while every comparison inside a run stayed valid.",
        "",
    ]


def render(ev: dict[str, Any], sw: dict[str, Any]) -> str:
    lines: list[str] = []
    lines += headline(ev, sw)
    lines += policy_table(ev)
    lines += waste_breakdown(ev)
    lines += ablations(sw)
    lines += sensitivity(sw)
    lines += reproducing(ev, sw)
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--eval", type=Path, default=EVAL)
    parser.add_argument("--sweep", type=Path, default=SWEEP)
    parser.add_argument("--out", type=Path, default=OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the rendered output differs from what is on disk",
    )
    args = parser.parse_args(argv)

    text = render(load(args.eval), load(args.sweep))

    if args.check:
        if not args.out.exists():
            print(f"{args.out} does not exist; run without --check first.", file=sys.stderr)
            return 1
        if args.out.read_text(encoding="utf-8") != text:
            print(
                f"{args.out} is out of date with the results files. "
                f"Run: python {Path(__file__).name}",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out} is up to date with the results files.")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"written to {args.out} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
